let lang = 'en';
try {
  const saved = localStorage.getItem('mv-lang');
  lang = saved || ((navigator.language || 'en').toLowerCase().startsWith('it') ? 'it' : 'en');
} catch (e) {
  lang = (typeof navigator !== 'undefined' && (navigator.language || '').toLowerCase().startsWith('it')) ? 'it' : 'en';
}

export const getLang = () => lang;
export function setLang(l) {
  lang = STR[l] ? l : 'en';
  try { localStorage.setItem('mv-lang', lang); } catch (e) { /* ignore */ }
}

// t('key', {name: value}) or t('key', [v0, v1])
export function t(key, vars) {
  let s = (STR[lang] && STR[lang][key]) ?? STR.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(v);
  return s;
}
